/**
 * Deterministic TypeScript emitters for the generated ABI modules.
 *
 * The emitters only consume the public ContractMetadata shape from
 * src/types.ts. Keeping them pure makes `bun run generate --check` reliable:
 * the same qubic/core commit must always produce byte-identical output.
 */

import type {
	ContractCall,
	ContractDefinition,
	ContractEnum,
	ContractField,
	ContractMetadata,
	ContractStruct,
} from '../../src/types.js'

const HEADER = (commit: string) =>
	`// @generated by scripts/generate.ts from qubic/core ${commit}. Do not edit by hand.\n`

export function emitMetadata(metadata: ContractMetadata): string {
	const body = JSON.stringify(metadata, null, 2)
	return `${HEADER(metadata.source.commit)}
import type { ContractDefinition, ContractMetadata } from "../types.js";

export const CONTRACT_METADATA: ContractMetadata = ${body};

export const CONTRACTS: readonly ContractDefinition[] = CONTRACT_METADATA.contracts;

export const CONTRACTS_BY_INDEX: Readonly<Record<number, ContractDefinition>> =
	Object.fromEntries(CONTRACTS.map((contract) => [contract.index, contract]));

export const CONTRACTS_BY_NAME: Readonly<Record<string, ContractDefinition>> =
	Object.fromEntries(CONTRACTS.map((contract) => [contract.name, contract]));
`
}

export function emitTypes(
	contracts: ContractDefinition[],
	commit: string,
): string {
	const chunks: string[] = [
		`${HEADER(commit)}
/* eslint-disable */
/* biome-ignore-all lint: generated file */

export type AbiInputScalar = number | bigint | boolean | string | Uint8Array
`,
	]

	for (const contract of contracts) {
		for (const call of allCalls(contract)) {
			for (const side of ['input', 'output'] as const) {
				const name = typeName(contract, call, side)
				const fields = side === 'input' ? call.inputFields : call.outputFields
				chunks.push(emitInterface(name, fields, contract, side))
			}
		}
		chunks.push(emitShape(contract))
	}

	chunks.push(
		`export interface ContractShapes {\n${contracts.map((contract) => `\t${contract.name}: ${shapeName(contract)}`).join('\n')}\n}\n`,
	)

	return chunks.join('\n')
}

export function emitContracts(
	contracts: ContractDefinition[],
	commit: string,
): string {
	const imports = contracts.map((contract) => shapeName(contract)).join(',\n\t')
	const definitions = contracts
		.map(
			(contract, index) =>
				`export const ${contract.name} = defineContract<${shapeName(contract)}>(CONTRACTS[${index}]!)`,
		)
		.join('\n\n')

	return `${HEADER(commit)}
import { defineContract } from "../abi.js";
import { CONTRACTS } from "./metadata.js";
import type {
	${imports},
} from "./types.js";

${definitions}

export const CONTRACT_HANDLES = [
${contracts.map((contract) => `\t${contract.name}`).join(',\n')},
] as const;

export const CONTRACT_HANDLES_BY_NAME = {
${contracts.map((contract) => `\t${contract.name}`).join(',\n')},
} as const;
`
}

export function emitQpi(commit: string): string {
	return `${HEADER(commit)}
import { createStructNamespace } from "../abi.js";
import { CONTRACT_METADATA } from "./metadata.js";

export const QPI_STRUCTS = CONTRACT_METADATA.qpi?.structs ?? {};
export const QPI_ENUMS = CONTRACT_METADATA.qpi?.enums ?? {};

/** Shared QPI structs and enums, addressed by qualified or short name. */
export const qpi = createStructNamespace("QPI", CONTRACT_METADATA.qpi);
`
}

export function emitGeneratedIndex(commit: string): string {
	return `${HEADER(commit)}
export * from "./metadata.js";
export * from "./types.js";
export * from "./contracts.js";
export * from "./qpi.js";
`
}

function allCalls(contract: ContractDefinition): ContractCall[] {
	return [
		...contract.procedures,
		...contract.functions,
		...contract.notifications,
	]
}

function shapeName(contract: ContractDefinition): string {
	return `${contract.name}Shape`
}

function typeName(
	contract: ContractDefinition,
	call: ContractCall,
	side: 'input' | 'output',
): string {
	return `${contract.name}_${call.name}_${side}`
}

function emitInterface(
	name: string,
	fields: ContractField[],
	contract: ContractDefinition,
	side: 'input' | 'output',
): string {
	if (fields.length === 0) {
		return `export type ${name} = Record<string, never>\n`
	}

	const lines = fields.map((field) => {
		const description = field.description
			? `\t/** ${field.description.replace(/\*\//g, '*\\/')} */\n`
			: ''
		return `${description}\t${propertyName(field.name)}: ${fieldType(field, contract, side)}`
	})

	return `export interface ${name} {\n${lines.join('\n')}\n}\n`
}

function emitShape(contract: ContractDefinition): string {
	const group = (calls: ContractCall[]) =>
		calls
			.map(
				(call) =>
					`\t\t${propertyName(call.name)}: { input: ${typeName(contract, call, 'input')}; output: ${typeName(contract, call, 'output')} }`,
			)
			.join('\n')

	return `export interface ${shapeName(contract)} {\n\tprocedures: {\n${group(contract.procedures)}\n\t}\n\tfunctions: {\n${group(contract.functions)}\n\t}\n\tnotifications: {\n${group(contract.notifications)}\n\t}\n}\n`
}

/** TypeScript type for one ABI field. */
function fieldType(
	field: ContractField,
	contract: ContractDefinition,
	side: 'input' | 'output',
): string {
	switch (field.type) {
		case 'uint8':
		case 'sint8':
		case 'uint16':
		case 'sint16':
		case 'uint32':
		case 'sint32':
			return 'number'
		case 'uint64':
		case 'sint64':
		case 'uint128':
			return 'bigint'
		case 'bit':
		case 'bool':
			return 'boolean'
		case 'id':
			return side === 'input' ? 'string | Uint8Array' : 'string'
		case 'enum':
			return 'number | string'
		case 'struct': {
			const struct = resolveStruct(field.structRef, contract)
			if (!struct)
				throw new Error(`Unknown struct reference: ${field.structRef}`)
			return inlineStruct(struct, contract, side)
		}
		case 'array': {
			const item = field.array
			if (!item)
				throw new Error(`Array field ${field.name} is missing array metadata`)
			let itemType: string
			switch (item.itemType) {
				case 'uint8':
				case 'sint8':
				case 'uint16':
				case 'sint16':
				case 'uint32':
				case 'sint32':
					itemType = 'number'
					break
				case 'uint64':
				case 'sint64':
				case 'uint128':
					itemType = 'bigint'
					break
				case 'bit':
				case 'bool':
					itemType = 'boolean'
					break
				case 'id':
					itemType = side === 'input' ? 'string | Uint8Array' : 'string'
					break
				case 'enum':
					itemType = 'number | string'
					break
				case 'struct': {
					const struct = resolveStruct(item.itemStructRef, contract)
					if (!struct)
						throw new Error(
							`Unknown array struct reference: ${item.itemStructRef}`,
						)
					itemType = inlineStruct(struct, contract, side)
					break
				}
			}
			return side === 'input' ? `readonly (${itemType})[]` : `(${itemType})[]`
		}
	}
}

function inlineStruct(
	struct: ContractStruct,
	contract: ContractDefinition,
	side: 'input' | 'output',
): string {
	if (struct.fields.length === 0) return 'Record<string, never>'
	const fields = struct.fields
		.map(
			(field) =>
				`${propertyName(field.name)}: ${fieldType(field, contract, side)}`,
		)
		.join('; ')
	return `{ ${fields} }`
}

function resolveStruct(
	ref: string | undefined,
	contract: ContractDefinition,
): ContractStruct | undefined {
	if (!ref) return undefined
	return contract.structs[ref]
}

function propertyName(name: string): string {
	return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name)
}

/** Exported for tests. */
export function scalarTypeScriptType(
	field: ContractField,
	side: 'input' | 'output',
): string {
	switch (field.type) {
		case 'uint8':
		case 'sint8':
		case 'uint16':
		case 'sint16':
		case 'uint32':
		case 'sint32':
			return 'number'
		case 'uint64':
		case 'sint64':
		case 'uint128':
			return 'bigint'
		case 'bit':
		case 'bool':
			return 'boolean'
		case 'id':
			return side === 'input' ? 'string | Uint8Array' : 'string'
		case 'enum':
			return 'number | string'
		default:
			throw new Error(`Not a scalar field: ${field.type}`)
	}
}

/** Metadata that may be useful to consumers without walking contract objects. */
export interface GeneratedSummary {
	contractCount: number
	procedureCount: number
	functionCount: number
	notificationCount: number
}

export function summarize(contracts: ContractDefinition[]): GeneratedSummary {
	return {
		contractCount: contracts.length,
		procedureCount: contracts.reduce(
			(sum, contract) => sum + contract.procedures.length,
			0,
		),
		functionCount: contracts.reduce(
			(sum, contract) => sum + contract.functions.length,
			0,
		),
		notificationCount: contracts.reduce(
			(sum, contract) => sum + contract.notifications.length,
			0,
		),
	}
}

